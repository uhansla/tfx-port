"""Merge code self-modification observed at run time into tools/smc/<EXE>.txt.

usage: py tools/smc_merge.py EXE RUNTIME_LOG

The runtime's live `c` command logs 'smc LOADADDR HEXBYTES' for every code byte
that differs from the loaded image.  This converts load addresses to link
addresses (what the analyzer works in) and adds them to the per-executable
list, which tools/recomp.py feeds to the analyzer: instructions overlapping
those bytes are then executed with their live bytes.  Lists from several runs
accumulate (different screens / game states patch different code).
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from le import LE                        # noqa: E402
from recomp import default_bases         # noqa: E402


def main():
    exe, log = sys.argv[1], sys.argv[2]
    le = LE(exe)
    bases = default_bases(exe)
    objs = [(bases[o.idx], o.link_base, o.vsize) for o in le.objs]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'smc', os.path.basename(exe).upper() + '.txt')
    known = {}
    if os.path.exists(out):
        for line in open(out):
            f = line.split('#')[0].split()
            if len(f) == 2:
                a = int(f[0], 16)
                for i, b in enumerate(bytes.fromhex(f[1])):
                    known[a + i] = b
    before = len(known)
    for line in open(log, errors='replace'):
        f = line.split()
        if len(f) != 3 or f[0] != 'smc' or f[1].endswith(':'):
            continue
        a = int(f[1], 16)
        for lb, link, size in objs:
            if lb <= a < lb + size:
                a = a - lb + link
                break
        else:
            continue
        for i, b in enumerate(bytes.fromhex(f[2])):
            known[a + i] = b
    # write back as runs of consecutive bytes
    lines, addrs = [], sorted(known)
    i = 0
    while i < len(addrs):
        j = i
        while j + 1 < len(addrs) and addrs[j + 1] == addrs[j] + 1 and j - i < 31:
            j += 1
        lines.append(f'{addrs[i]:08x} ' + bytes(known[a] for a in addrs[i:j + 1]).hex())
        i = j + 1
    with open(out, 'w') as fh:
        fh.write(f'# {os.path.basename(exe)}: code bytes seen modified at run time (link addresses,\n'
                 '# last value seen).  Generated by tools/smc_merge.py; feeds tools/recomp.py.\n')
        fh.write('\n'.join(lines) + '\n')
    print(f'{out}: {len(known)} bytes ({len(known) - before} new)')


if __name__ == '__main__':
    main()
